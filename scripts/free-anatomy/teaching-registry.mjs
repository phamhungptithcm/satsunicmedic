// Run after full-body-convert.mjs. Derive persistence validation from the exact renderer catalog.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const path='.ai/local/free-anatomy/full-body-v3/conversion.json';
const catalog=JSON.parse(await readFile(path,'utf8'));
const canonical=JSON.stringify(catalog);
const data={version:catalog.version,hash:createHash('sha256').update(canonical).digest('hex'),reviewStatus:catalog.reviewStatus,structures:Object.keys(catalog.structures),concepts:Object.keys(catalog.concepts),regions:Object.keys(catalog.regions),systems:Object.keys(catalog.systems)};
await writeFile('packages/contracts/src/body-registry.ts',`// Generated by scripts/free-anatomy/teaching-registry.mjs; do not edit.\nexport const bodyRegistry = ${JSON.stringify(data)};\n`);
console.log(JSON.stringify({version:data.version,hash:data.hash,structures:data.structures.length}));
